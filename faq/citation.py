"""faq/citation.py — the "Source:" line is appended by CODE, deck slide 6.

Rule from the architecture deck: the model may rephrase, but the citation
line itself is generated by code from the winning section's heading, and
the answer's quoted text is verified to exist in that section. An answer
whose quote cannot be found in the KB never ships with a citation — the
verifier drops it, exactly like graphrag_demo/citation.py did.
"""

from __future__ import annotations


def cite(section) -> str:
    return f"Source: {section.title}"


def grounded(answer_text: str, section) -> bool:
    """Every line/sentence we claim to quote must appear in the section body.

    The deterministic composer emits one line per KB line, so grounding is
    per line; a model-composed paragraph is checked per sentence. Text
    under 25 characters is framing ("Payment methods:") — not a claim.
    """
    body = " ".join((section.title + " " + section.text).lower().split())
    for line in answer_text.splitlines():
        for sentence in _sentences(line):
            norm = " ".join(sentence.lower().split())
            if len(norm) > 25 and norm not in body:
                return False
    return True


def _sentences(text: str) -> list[str]:
    parts = [p.strip() for p in text.replace("\n", " ").split(".") if p.strip()]
    # Keep only sentences that look like quotes, not our own framing words.
    return parts
